import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(repositoryRoot, 'shared/asset-catalog.json');
const swiftPath = path.join(
	repositoryRoot,
	'apple/KARA/KARA/Domain/Assets/AssetCatalog.generated.swift'
);
const typescriptPath = path.join(
	repositoryRoot,
	'website/src/lib/server/asset-extraction/catalog.generated.ts'
);
const checkOnly = process.argv.includes('--check');

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
validate(manifest);

const outputs = [
	[swiftPath, renderSwift(manifest)],
	[typescriptPath, renderTypeScript(manifest)]
];

if (checkOnly) {
	const stale = [];
	for (const [outputPath, expected] of outputs) {
		const actual = await readFile(outputPath, 'utf8').catch(() => '');
		if (actual !== expected) stale.push(path.relative(repositoryRoot, outputPath));
	}
	if (stale.length > 0) {
		throw new Error(`Generated asset catalog is stale: ${stale.join(', ')}`);
	}
} else {
	await Promise.all(outputs.map(([outputPath, contents]) => writeFile(outputPath, contents)));
}

function validate(value) {
	if (!value || !Array.isArray(value.presets) || value.presets.length === 0) {
		throw new Error('Asset catalog must contain presets');
	}
	const identifiers = new Set();
	for (const preset of value.presets) {
		if (!preset.id || identifiers.has(preset.id)) throw new Error(`Invalid or duplicate preset: ${preset.id}`);
		identifiers.add(preset.id);
		if (!['bar', 'coin', 'jewelry', 'custom'].includes(preset.category)) {
			throw new Error(`Invalid category for ${preset.id}`);
		}
		if (preset.metal !== null && !['gold', 'silver', 'platinum', 'palladium', 'other'].includes(preset.metal)) {
			throw new Error(`Invalid metal for ${preset.id}`);
		}
	}
	for (const tolerance of Object.values(value.compatibility ?? {})) {
		if (tolerance.relativeTolerance < 0 || tolerance.absoluteTolerance < 0) {
			throw new Error('Catalog tolerances must be non-negative');
		}
	}
}

function renderSwift({ compatibility, presets }) {
	const entries = presets.map((preset) => `        AssetPreset(
            id: ${swiftString(preset.id)},
            name: ${swiftString(preset.name)},
            category: .${preset.category},
            metal: ${preset.metal === null ? 'nil' : `.${preset.metal}`},
            weightGrams: ${swiftValue(preset.weightGrams)},
            metalKarat: ${swiftValue(preset.metalKarat)},
            finenessPermille: ${swiftValue(preset.finenessPermille)}
        )`).join(',\n');

	return `// Generated from shared/asset-catalog.json by scripts/generate-asset-catalog.mjs.
// Do not edit this file directly.

extension AssetCatalog {
    nonisolated static let presets: [AssetPreset] = [
${entries},
    ]
}

extension AssetPresetCompatibility {
    nonisolated static let weightRelativeTolerance: Double = ${compatibility.weightGrams.relativeTolerance}
    nonisolated static let weightAbsoluteTolerance: Double = ${compatibility.weightGrams.absoluteTolerance}
    nonisolated static let finenessRelativeTolerance: Double = ${compatibility.finenessPermille.relativeTolerance}
    nonisolated static let finenessAbsoluteTolerance: Double = ${compatibility.finenessPermille.absoluteTolerance}
}
`;
}

function renderTypeScript({ compatibility, presets }) {
	return `// Generated from shared/asset-catalog.json by scripts/generate-asset-catalog.mjs.\n` +
		`// Do not edit this file directly.\n\n` +
		`export const ASSET_CATALOG = ${JSON.stringify(presets, null, '\t')} as const;\n\n` +
		`export const ASSET_PRESET_COMPATIBILITY = ${JSON.stringify(compatibility, null, '\t')} as const;\n`;
}

function swiftString(value) {
	return JSON.stringify(value).replaceAll('\\/', '/');
}

function swiftValue(value) {
	return value === null ? 'nil' : String(value);
}
